declare
    table_name text;
    action_name text;
begin
    foreach table_name in array array[
        'regions', 'countries', 'attractions', 'accommodations', 'restaurants', 'tour_operators',
        'page_sections', 'site_settings'
    ]
    loop
        foreach action_name in array array['insert', 'update', 'delete']
