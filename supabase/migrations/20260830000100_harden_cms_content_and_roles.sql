create or replace function private.has_cms_role(required_roles text[])
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
    select exists (
        select 1
        from public.profiles
        where id = (select auth.uid())
          and role = any(required_roles)
    );
$$;

revoke execute on function private.has_cms_role(text[]) from public;
grant usage on schema private to authenticated;
grant execute on function private.has_cms_role(text[]) to authenticated;

create or replace function public.is_admin()
returns boolean
language sql
stable
security invoker
set search_path = ''
as $$
    select private.has_cms_role(array['admin', 'super_admin']);
$$;

revoke execute on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

