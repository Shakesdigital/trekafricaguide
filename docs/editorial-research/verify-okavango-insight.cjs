add('title', html.includes('Plan an Okavango trip: water camp, land camp, or a Maun day'));
const h3s = (html.match(/<h2[^>]*>|<h3[^>]*>[^<]+<\/h3>/g) || []).map(x => x.replace(/<\/?h3[^>]*>/g, '').replace(/<[^>]+>/g, ''));
console.log('HEADINGS:', JSON.stringify([...new Set(h3s.filter(Boolean))]));
add('decision sections', ['Ask what the water will allow', 'Water camp, land camp, or a complementary pair', 'Getting there: Maun, then the planes', 'Timing: read the flood, not just the calendar', 'Build the pace, then ask before you pay'].every(s => html.includes(s)));
const imgs = (html.match(/\/images\/editorial\/okavango-trip-planning\/[a-z0-9-]+\.jpg/g) || []);
add('six gallery assets referenced', new Set(imgs).size === 6);
add('figure captions with licences', (html.match(/Wikimedia Commons/g) || []).length >= 5);
add('UNESCO facts render', html.includes('2014') && html.includes('1,000th') && html.includes('June/July'));
add('internal links', ['/attractions/okavango-delta', '/activities/okavango-mokoro-safari', '/accommodations/camp-okavango', '/countries/botswana/maun', '/countries/botswana'].every(s => html.includes(s)));
add('no booking CTA', !/[a-z]+="[^"]*(booking\.com|stay22)/i.test(html.replace(/<!--[\s\S]*?-->/g, '').replace(/<(script|style)[\s\S]*?<\/\1>/g, '')));
add('no markup leak', !html.includes('&lt;p&gt;') && !html.includes('&lt;h3&gt;') && !html.includes('&lt;figure&gt;'));
add('hero image', html.includes('/images/editorial/okavango-trip-planning/okavango-zebra-aerial-helicopter-2018.jpg'));
add('archive listing', fs.readFileSync('dist/travel-insights/index.html', 'utf8').includes('plan-okavango-trip-water-and-land-camps'));
console.log(checks.join('\n'));
console.log(imgs.join('\n'));
if (checks.some(c => c.startsWith('FAIL'))) process.exit(1);
